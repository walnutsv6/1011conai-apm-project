#!/usr/bin/env python3
"""Build novelai-imagegen request files for an undressing sequence (stage ladder).

Usage:
  python build_requests.py --spec spec.json --project-dir output/novelai-imagegen/<project>
         [--user-run-dir user-run-scripts] [--only mia] [--stage s1,s2] [--rating sensitive] [--suffix v2]

Stages of class clothed / partial / underwear are written to <project-dir>/requests/ and are
generated by the agent. Stages of class topless / bottomless / nude are SCRIPT-ONLY: their requests
and run.ps1 / run.sh go to <user-run-dir>/<character>-<theme>/ and are executed by the user, never
by the agent. Existing request files are never overwritten (use --suffix v2 for a revision).
Writes <project-dir>/manifest.json (all expected cells) and <project-dir>/prompts.md.
"""
import argparse
import json
import os
import re
import sys
from pathlib import Path

TRANSPARENT_BG = "transparent background, simple background, no background"
TRANSPARENT_NEG = "scenery, background, outdoors"
DEFAULT_EXPOSED_EXPRESSION = "embarrassed, shy, blush"
CLASSES = ["clothed", "partial", "underwear", "topless", "bottomless", "nude"]
SCRIPT_ONLY = {"topless", "bottomless", "nude"}
PRIVATE_REQUIRED = {"underwear", "topless", "bottomless", "nude"}
CROTCH_CLASSES = {"bottomless", "nude"}
CLASS_LABEL = {"clothed": "着衣", "partial": "脱ぎかけ", "underwear": "下着", "topless": "トップレス",
               "bottomless": "ボトムレス", "nude": "ヌード"}


def join(*parts):
    return ", ".join(p.strip(" ,") for p in parts if p and p.strip(" ,"))


def rel(path, start):
    try:
        return os.path.relpath(path, start).replace("\\", "/")
    except ValueError:  # different drive on Windows
        return Path(path).resolve().as_posix()


def slug(s):
    return re.sub(r"[^A-Za-z0-9_]+", "", s)


def die(msg):
    print(f"error: {msg}", file=sys.stderr)
    sys.exit(2)


def validate(spec):
    d = spec["defaults"]
    if "adult" not in d["base_tags"]:
        die("defaults.base_tags must keep an adult tag (e.g. 'mature female, adult woman, 20s')")
    if "child" not in d["common_negative"]:
        die("defaults.common_negative must keep 'child, loli' guards")
    if d.get("pose_mode", "fixed") not in ("fixed", "per_stage"):
        die("defaults.pose_mode must be 'fixed' or 'per_stage'")
    if d.get("pose_mode", "fixed") == "fixed" and d.get("fixed_pose") not in spec["poses"]:
        die("pose_mode 'fixed' needs defaults.fixed_pose naming an entry in poses")
    seen = set()
    for st in spec["stages"]:
        if not re.fullmatch(r"[A-Za-z0-9_]+", st["id"]):
            die(f"stage id '{st['id']}' must be [A-Za-z0-9_] only (it becomes part of the file name)")
        if st["id"] in seen:
            die(f"duplicate stage id '{st['id']}'")
        seen.add(st["id"])
        if st["class"] not in CLASSES:
            die(f"stage '{st['id']}': class must be one of {CLASSES}")
        if st["class"] in CROTCH_CLASSES and st.get("crotch") not in ("covered", "open", "both"):
            die(f"stage '{st['id']}' ({st['class']}): set crotch to covered / open / both (ask the user)")
        if d.get("pose_mode", "fixed") == "per_stage" and st.get("pose") not in spec["poses"]:
            die(f"stage '{st['id']}': pose_mode is per_stage, so stage.pose must name an entry in poses")
    classes = [s["class"] for s in spec["stages"]]
    if not any(c in ("clothed", "partial", "underwear") for c in classes):
        die("the sequence must include clothed / partial / underwear stages (a nude-only set is out of scope)")
    if classes[0] not in ("clothed", "underwear"):
        die("the first stage must be clothed or underwear (the sequence starts dressed)")
    for cname, ch in spec["characters"].items():
        missing = [s["id"] for s in spec["stages"] if s["id"] not in ch["stages"]]
        if missing:
            die(f"{cname}: missing stage tags for {missing}")
        if "bangs" not in ch["appearance"]:
            print(f"warning: {cname}: appearance has no bangs tag; fringe may vary between stages", file=sys.stderr)
        if "modes" not in d or "bg" in d["modes"]:
            if not ch.get("scene_private") and any(c in PRIVATE_REQUIRED for c in classes):
                die(f"{cname}: stages from underwear onward need a private, hard-to-enter scene; "
                    f"pick one (bedroom, changing room, hotel room...) and set scene_private: true")


def cells(stage):
    """-> list of variant names for the stage ('' when the stage has none)."""
    if stage["class"] not in CROTCH_CLASSES:
        return [""]
    return {"covered": ["covered"], "open": ["open"], "both": ["covered", "open"]}[stage["crotch"]]


def find_override(char, stage, mode, variant):
    merged = {}
    for ov in char.get("overrides", []):
        m = ov.get("match", {})
        if all(m.get(k) in (None, v) for k, v in (("stage", stage), ("mode", mode), ("variant", variant))):
            for k, v in ov.items():
                if k == "match":
                    continue
                merged[k] = join(merged[k], v) if k.startswith("append_") and k in merged else v
    return merged


def build(spec, cname, char, stage, variant, mode, rating, suffix):
    d = spec["defaults"]
    cls = stage["class"]
    ov = find_override(char, stage["id"], mode, variant)
    pose_id = d["fixed_pose"] if d.get("pose_mode", "fixed") == "fixed" else stage["pose"]
    pose_def = spec["poses"][pose_id]

    background = TRANSPARENT_BG if mode == "transparent" else char["scene"]
    appearance = join(char["appearance"], ov.get("append_appearance", ""))
    stage_tags = join(ov.get("replace_stage", char["stages"][stage["id"]]), ov.get("append_stage", ""))
    pose_expr = ov.get("replace_pose_expression", pose_def.get("expression", ""))
    if cls in SCRIPT_ONLY:  # topless onward: shy/blush by default (defaults.exposed_expression, "" disables)
        have = {t.strip() for t in pose_expr.split(",")}
        extra = [t.strip() for t in d.get("exposed_expression", DEFAULT_EXPOSED_EXPRESSION).split(",")]
        pose_expr = join(pose_expr, ", ".join(t for t in extra if t and t not in have))
    body = join(char.get("body", ""), ov.get("append_body", ""))

    cover = d.get("covered_tags", "covering crotch") if variant == "covered" else ""
    if cls in ("topless", "nude"):
        rating_tags = f"rating:explicit, nipples"
    elif cls == "bottomless":
        rating_tags = "rating:explicit"
    else:
        rating_tags = f"rating:{stage.get('rating', rating)}"

    prompt = join(
        background, d["base_tags"], appearance, char.get("expression", ""), stage_tags,
        ov.get("replace_composition", d["composition"]), pose_def["tags"], cover, pose_expr, d["gaze"],
        body, d["style"], rating_tags,
    )

    if cls in SCRIPT_ONLY:
        class_neg = d["exposed_negative"]
    else:
        class_neg = d["clothed_negative"]
    negative = join(
        char.get("negative", ""), ov.get("append_negative", ""), stage.get("negative", ""), class_neg,
        TRANSPARENT_NEG if mode == "transparent" else "", d["common_negative"],
    )

    note = re.sub(r"[^A-Za-z0-9_-]+", "-", ov["note"]).strip("-") if ov.get("note") else None
    stem = "-".join([cname, stage["id"], pose_id, mode] + ([variant] if variant else []))
    basename = "-".join([stem] + ([note] if note else []) + ([suffix] if suffix else []))

    req = {
        "schema_version": 1,
        "operation": "generate",
        "prompt": prompt,
        "negative_prompt": negative,
        "model": d["model"],
        "orientation": d["orientation"],
        "seed": ov.get("seed", char["seed"]),
        "steps": d["steps"],
        "scale": d["scale"],
        "samples": 1,
        "cost_policy": {
            "subscription_plan": "auto",
            "prefer_zero_anlas": True,
            "require_zero_anlas": d.get("require_zero_anlas", True),
            "confirm_above_anlas": 100,
            "confirmed_paid": False,
        },
        "output": {"basename": basename, "character": cname, "format": "png"},
    }
    if mode == "transparent":
        req["straight_alpha"] = True
        req["tag_hint_transparent_background"] = True
    return stem, basename, pose_id, req


PS1 = r"""# User-run batch for {title}. The agent does NOT run this script.
# 1) Set the key for this session only (never save it in a file):
#      $env:NOVELAI_API_KEY = "<your NovelAI API key>"
# 2) Run from anywhere:
#      powershell -ExecutionPolicy Bypass -File "{self_rel}"
$ErrorActionPreference = 'Stop'
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
$root = (Resolve-Path (Join-Path $here '{up}')).Path
Set-Location $root
if (-not $env:NOVELAI_API_KEY) {{ Write-Error 'NOVELAI_API_KEY is not set.'; exit 1 }}
if (-not (Get-Command uv -ErrorAction SilentlyContinue)) {{ Write-Error 'uv is not installed.'; exit 1 }}
$runner = '{runner}'
$has = '{has}'
$out = '{images}'
uv run $runner validate
if ($LASTEXITCODE -ne 0) {{ exit $LASTEXITCODE }}
foreach ($f in Get-ChildItem (Join-Path $here 'requests') -Filter '*.request.json' | Sort-Object Name) {{
  Write-Host "== $($f.Name)"
  python $has --request $f.FullName --out-dir $out
  if ($LASTEXITCODE -eq 0) {{ Write-Host 'already generated; skipping'; continue }}
  uv run $runner estimate --request $f.FullName
  if ($LASTEXITCODE -ne 0) {{ Write-Warning "estimate failed; skipping $($f.Name)"; continue }}
  uv run $runner generate --request $f.FullName --out-dir $out
  if ($LASTEXITCODE -ne 0) {{ Write-Warning "generate skipped or failed for $($f.Name)" }}
}}
"""

SH = r"""#!/usr/bin/env bash
# User-run batch for {title}. The agent does NOT run this script.
# export NOVELAI_API_KEY="<your NovelAI API key>"   # this shell only, never save it in a file
set -u
here="$(cd "$(dirname "${{BASH_SOURCE[0]}}")" && pwd)"
cd "$here/{up}"
[ -n "${{NOVELAI_API_KEY:-}}" ] || {{ echo "NOVELAI_API_KEY is not set." >&2; exit 1; }}
command -v uv >/dev/null || {{ echo "uv is not installed." >&2; exit 1; }}
runner='{runner}'
has='{has}'
out='{images}'
uv run "$runner" validate || exit $?
for f in "$here"/requests/*.request.json; do
  echo "== $(basename "$f")"
  if python "$has" --request "$f" --out-dir "$out"; then echo "already generated; skipping"; continue; fi
  uv run "$runner" estimate --request "$f" || {{ echo "estimate failed; skipping" >&2; continue; }}
  uv run "$runner" generate --request "$f" --out-dir "$out" || echo "generate skipped or failed" >&2
done
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--spec", required=True)
    ap.add_argument("--project-dir", required=True)
    ap.add_argument("--user-run-dir", default="user-run-scripts")
    ap.add_argument("--only", help="comma-separated character names")
    ap.add_argument("--stage", help="comma-separated stage ids")
    ap.add_argument("--rating", help="override defaults.rating for non-explicit stages")
    ap.add_argument("--suffix", default="", help="revision suffix, e.g. v2")
    args = ap.parse_args()

    spec = json.loads(Path(args.spec).read_text(encoding="utf-8"))
    validate(spec)
    cwd = Path.cwd()
    project = Path(args.project_dir)
    req_dir = project / "requests"
    req_dir.mkdir(parents=True, exist_ok=True)
    rating = args.rating or spec["defaults"].get("rating", "sensitive")
    modes = spec["defaults"].get("modes", ["bg", "transparent"])
    only = set(args.only.split(",")) if args.only else None
    only_stage = set(args.stage.split(",")) if args.stage else None
    theme = slug(spec.get("theme", "undress")) or "undress"
    skills_root = Path(__file__).resolve().parents[2]
    runner = rel(skills_root / "novelai-imagegen" / "scripts" / "novelai_image.py", cwd)
    has = rel(skills_root / "novelai-strip-sequence" / "scripts" / "has_output.py", cwd)
    images = rel(project / "images", cwd)

    manifest, md, written, skipped = [], [], 0, 0
    user_dirs = {}
    for cname, char in spec["characters"].items():
        if only and cname not in only:
            continue
        md += [f"## {cname} (seed `{char['seed']}`, pose: {spec['defaults'].get('pose_mode', 'fixed')})", ""]
        for stage in spec["stages"]:
            script_only = stage["class"] in SCRIPT_ONLY
            for variant in cells(stage):
                for mode in modes:
                    stem, base, pose_id, req = build(spec, cname, char, stage, variant, mode, rating, args.suffix)
                    if script_only:
                        udir = user_dirs.setdefault(cname, Path(args.user_run_dir) / f"{cname}-{theme}")
                        target = udir / "requests"
                    else:
                        target = req_dir
                    path = target / f"{base}.request.json"
                    if not only_stage or stage["id"] in only_stage:
                        target.mkdir(parents=True, exist_ok=True)
                        if path.exists():
                            skipped += 1
                        else:
                            path.write_text(json.dumps(req, ensure_ascii=False, indent=2), encoding="utf-8")
                            written += 1
                    manifest.append({
                        "character": cname, "stage": stage["id"], "label": stage.get("label", stage["id"]),
                        "class": stage["class"], "class_label": CLASS_LABEL[stage["class"]],
                        "variant": variant, "pose": pose_id, "mode": mode, "stem": stem,
                        "seed": req["seed"], "script_only": script_only,
                        "request": rel(path, cwd),
                    })
                    tag = " ※ユーザー実行" if script_only else ""
                    md += [f"### {base}{tag}", "", f"class: `{stage['class']}` / variant: `{variant or '-'}`", "",
                           "```", req["prompt"], "```", "", f"negative: `{req['negative_prompt']}`", ""]

    for cname, udir in user_dirs.items():
        reqs = list((udir / "requests").glob("*.request.json")) if (udir / "requests").exists() else []
        if not reqs:
            continue
        title = f"{cname} / {theme}"
        up = rel(cwd, udir)
        kw = dict(title=title, up=up, runner=runner, images=images, has=has)
        for name, tpl in (("run.ps1", PS1), ("run.sh", SH)):
            sp = udir / name
            if not sp.exists():
                sp.write_text(tpl.format(self_rel=(udir / name).as_posix(), **kw), encoding="utf-8", newline="\n")

    (project / "manifest.json").write_text(json.dumps(
        {"project": spec.get("project", project.name), "theme": spec.get("theme", ""),
         "pose_mode": spec["defaults"].get("pose_mode", "fixed"),
         "stages": [{"id": s["id"], "label": s.get("label", s["id"]), "class": s["class"],
                     "class_label": CLASS_LABEL[s["class"]]} for s in spec["stages"]],
         "cells": manifest}, ensure_ascii=False, indent=2), encoding="utf-8")
    (project / "prompts.md").write_text("# Prompts\n\n" + "\n".join(md), encoding="utf-8")
    print(json.dumps({"written": written, "skipped_existing": skipped, "cells": len(manifest),
                      "script_only_cells": sum(c["script_only"] for c in manifest),
                      "user_run_dirs": [str(p) for p in user_dirs.values()]}, ensure_ascii=False))


if __name__ == "__main__":
    sys.exit(main())
