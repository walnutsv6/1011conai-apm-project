#!/usr/bin/env python3
"""Build novelai-imagegen request files for a gravure CG book (cover + chapters of cuts).

Usage:
  python build_requests.py --spec spec.json --project-dir output/novelai-imagegen/<project>
         [--user-run-dir user-run-scripts] [--chapter cover,ch1] [--rating sensitive] [--suffix v2]

The cover is generated by the agent: its request goes to <project-dir>/requests/. Every body cut
(any class, clothed to nude) is generated by the USER: requests, run.ps1 / run.sh, update-book.ps1 /
update-book.sh and README.txt go to <user-run-dir>/<character>-<theme>/. Existing request files are
never overwritten (use --suffix v2 for a revision). Writes <project-dir>/manifest.json (every
expected page cell, in order) and <project-dir>/prompts.md.
"""
import argparse
import json
import os
import re
import sys
from pathlib import Path

CLASSES = ["clothed", "partial", "swimsuit", "underwear", "topless", "bottomless", "nude"]
COVER_CLASSES = {"clothed", "partial", "swimsuit", "underwear"}
EXPOSED = {"topless", "bottomless", "nude"}
PRIVATE_REQUIRED = {"underwear", "topless", "bottomless", "nude"}
CROTCH_CLASSES = {"bottomless", "nude"}
CLASS_LABEL = {"clothed": "着衣", "partial": "脱ぎかけ", "swimsuit": "水着", "underwear": "下着",
               "topless": "トップレス", "bottomless": "ボトムレス", "nude": "ヌード"}
DEFAULT_EXPOSED_EXPRESSION = "embarrassed, shy, blush"
DEFAULT_BACK_TAGS = "from behind, looking back, back turned"
DEFAULT_SHOTS = {
    "closeup": {"tags": "close-up, portrait, face focus", "orientation": "portrait", "negative": "full body, wide shot"},
    "upper": {"tags": "upper body", "orientation": "portrait", "negative": "full body, wide shot"},
    "cowboy": {"tags": "cowboy shot", "orientation": "portrait", "negative": "full body, wide shot"},
    "full": {"tags": "full body", "orientation": "portrait", "negative": "close-up, cropped"},
    "lying": {"tags": "lying, on side, from above", "orientation": "landscape", "negative": "full body, wide shot"},
}


def join(*parts):
    return ", ".join(p.strip(" ,") for p in parts if p and p.strip(" ,"))


def rel(path, start):
    try:
        return os.path.relpath(path, start).replace("\\", "/")
    except ValueError:  # different drive on Windows
        return Path(path).resolve().as_posix()


def slug(s):
    return re.sub(r"[^A-Za-z0-9_]+", "", s)


def die(msg):
    print(f"error: {msg}", file=sys.stderr)
    sys.exit(2)


def shots_of(spec):
    merged = dict(DEFAULT_SHOTS)
    merged.update(spec["defaults"].get("shots", {}))
    return merged


def validate(spec):
    d, ch = spec["defaults"], spec["character"]
    shots = shots_of(spec)
    if "adult" not in d["base_tags"]:
        die("defaults.base_tags must keep an adult tag (e.g. 'mature female, adult woman, 20s')")
    if "child" not in d["common_negative"]:
        die("defaults.common_negative must keep 'child, loli' guards")
    if not re.fullmatch(r"[A-Za-z0-9_-]+", ch["name"]):
        die("character.name must be [A-Za-z0-9_-] only (it becomes a folder name)")
    src = ch.get("source")
    if src is not None:
        if src.get("canon_adult") is not True:
            die("character.source.canon_adult must be true. If the original character is a minor or the "
                "age is unconfirmed, do not use the character tag: make an original adult character instead")
        age = src.get("canon_age")
        if isinstance(age, int) and age < 18:
            die(f"character.source.canon_age is {age}; sexual content with a minor source character is out of scope")
        if not src.get("tag"):
            die("character.source.tag is required (the character tag to use as inspiration)")
    if "bangs" not in ch["appearance"]:
        print("warning: appearance has no bangs tag; fringe may vary between cuts", file=sys.stderr)

    def check_cut(where, cut, chapter_scene_private, default_outfit):
        if cut["class"] not in CLASSES:
            die(f"{where}: class must be one of {CLASSES}")
        if cut["pose"] not in spec["poses"]:
            die(f"{where}: pose '{cut['pose']}' is not in poses")
        if cut["shot"] not in shots:
            die(f"{where}: shot '{cut['shot']}' is not in {sorted(shots)}")
        if cut["class"] in PRIVATE_REQUIRED and not chapter_scene_private:
            die(f"{where}: class {cut['class']} needs a private, hard-to-enter scene "
                f"(set scene_private: true on the chapter/cover; a show-stage exception must be explicit)")
        if cut["class"] in CROTCH_CLASSES and cut.get("crotch") not in ("covered", "open", "both"):
            die(f"{where} ({cut['class']}): set crotch to covered / open / both (ask the user)")
        if cut["class"] in EXPOSED and cut.get("facing") not in ("front", "back"):
            die(f"{where} ({cut['class']}): set facing to front / back (ask the user; use two cuts for both)")
        if not (cut.get("outfit") or default_outfit):
            die(f"{where}: no outfit (give the cut or its chapter an outfit)")

    cover = spec["cover"]
    if cover["class"] not in COVER_CLASSES:
        die(f"cover.class must be one of {sorted(COVER_CLASSES)} (the cover is never topless/bottomless/nude)")
    check_cut("cover", cover, cover.get("scene_private"), cover.get("outfit"))
    seen = set()
    for chp in spec["chapters"]:
        if not re.fullmatch(r"[A-Za-z0-9_]+", chp["id"]) or chp["id"] == "cover":
            die(f"chapter id '{chp['id']}' must be [A-Za-z0-9_] only and not 'cover'")
        if chp["id"] in seen:
            die(f"duplicate chapter id '{chp['id']}'")
        seen.add(chp["id"])
        if chp.get("mode", "cuts") not in ("cuts", "strip"):
            die(f"chapter '{chp['id']}': mode must be cuts or strip")
        cut_ids = set()
        for cut in chp["cuts"]:
            if not re.fullmatch(r"[A-Za-z0-9_]+", cut["id"]) or cut["id"] in cut_ids:
                die(f"chapter '{chp['id']}': cut id '{cut['id']}' must be unique and [A-Za-z0-9_] only")
            cut_ids.add(cut["id"])
            if chp.get("mode", "cuts") == "strip" and not cut.get("outfit"):
                die(f"chapter '{chp['id']}' cut '{cut['id']}': strip mode needs an outfit on every cut")
            check_cut(f"{chp['id']}/{cut['id']}", cut, chp.get("scene_private"), chp.get("outfit"))


def variants(cut):
    if cut["class"] not in CROTCH_CLASSES:
        return [""]
    return {"covered": ["covered"], "open": ["open"], "both": ["covered", "open"]}[cut["crotch"]]


def build(spec, container, cut, variant, rating, suffix, stem):
    d, ch = spec["defaults"], spec["character"]
    cls = cut["class"]
    shot = shots_of(spec)[cut["shot"]]
    pose = spec["poses"][cut["pose"]]
    src = ch.get("source")
    appearance = ch["appearance"]
    if src:
        appearance = join(f"{src.get('tag_weight', 0.8)}::{src['tag']}::", appearance)

    pose_expr = pose.get("expression", "")
    if cls in EXPOSED:
        have = {t.strip() for t in pose_expr.split(",")}
        extra = [t.strip() for t in d.get("exposed_expression", DEFAULT_EXPOSED_EXPRESSION).split(",")]
        pose_expr = join(pose_expr, ", ".join(t for t in extra if t and t not in have))
    back = d.get("back_tags", DEFAULT_BACK_TAGS) if cut.get("facing") == "back" else ""
    cover_tags = d.get("covered_tags", "covering crotch") if variant == "covered" else ""
    if cls in ("topless", "nude"):
        rating_tags = "rating:explicit, nipples"
    elif cls == "bottomless":
        rating_tags = "rating:explicit"
    else:
        rating_tags = f"rating:{cut.get('rating', rating)}"

    prompt = join(
        container["scene"], d["base_tags"], appearance, ch.get("expression", ""),
        cut.get("outfit") or container["outfit"], shot["tags"], pose["tags"], cut.get("append_pose", ""),
        back, cover_tags, pose_expr, d["gaze"], ch.get("body", ""), d["style"], rating_tags,
    )
    class_neg = d["exposed_negative"] if cls in EXPOSED else d["clothed_negative"]
    negative = join(ch.get("negative", ""), cut.get("negative", ""), class_neg, shot.get("negative", ""),
                    d["common_negative"])

    note = re.sub(r"[^A-Za-z0-9_-]+", "-", cut["note"]).strip("-") if cut.get("note") else None
    basename = "-".join([stem] + ([note] if note else []) + ([suffix] if suffix else []))
    req = {
        "schema_version": 1,
        "operation": "generate",
        "prompt": prompt,
        "negative_prompt": negative,
        "model": d["model"],
        "orientation": cut.get("orientation", shot.get("orientation", "portrait")),
        "seed": cut.get("seed", ch["seed"]),
        "steps": d["steps"],
        "scale": d["scale"],
        "samples": 1,
        "cost_policy": {
            "subscription_plan": "auto",
            "prefer_zero_anlas": True,
            "require_zero_anlas": d.get("require_zero_anlas", True),
            "confirm_above_anlas": 100,
            "confirmed_paid": False,
        },
        "output": {"basename": basename, "character": ch["name"], "format": "png"},
    }
    return basename, req


PS1 = r"""# User-run batch for {title}. The agent does NOT run this script.
# 1) Set the key for this session only (never save it in a file):
#      $env:NOVELAI_API_KEY = "<your NovelAI API key>"
# 2) Run from anywhere:
#      powershell -ExecutionPolicy Bypass -File "{self_rel}"
# The book HTML ({index}) is rebuilt at the end.
$ErrorActionPreference = 'Stop'
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
$root = (Resolve-Path (Join-Path $here '{up}')).Path
Set-Location $root
if (-not $env:NOVELAI_API_KEY) {{ Write-Error 'NOVELAI_API_KEY is not set.'; exit 1 }}
if (-not (Get-Command uv -ErrorAction SilentlyContinue)) {{ Write-Error 'uv is not installed.'; exit 1 }}
$runner = '{runner}'
$has = '{has}'
$out = '{images}'
uv run $runner validate
if ($LASTEXITCODE -ne 0) {{ exit $LASTEXITCODE }}
foreach ($f in Get-ChildItem (Join-Path $here 'requests') -Filter '*.request.json' | Sort-Object Name) {{
  Write-Host "== $($f.Name)"
  python $has --request $f.FullName --out-dir $out
  if ($LASTEXITCODE -eq 0) {{ Write-Host 'already generated; skipping'; continue }}
  uv run $runner estimate --request $f.FullName
  if ($LASTEXITCODE -ne 0) {{ Write-Warning "estimate failed; skipping $($f.Name)"; continue }}
  uv run $runner generate --request $f.FullName --out-dir $out
  if ($LASTEXITCODE -ne 0) {{ Write-Warning "generate skipped or failed for $($f.Name)" }}
}}
python '{book}' --project-dir '{project}' --title '{book_title}'
"""

SH = r"""#!/usr/bin/env bash
# User-run batch for {title}. The agent does NOT run this script.
# export NOVELAI_API_KEY="<your NovelAI API key>"   # this shell only, never save it in a file
# The book HTML ({index}) is rebuilt at the end.
set -u
here="$(cd "$(dirname "${{BASH_SOURCE[0]}}")" && pwd)"
cd "$here/{up}"
[ -n "${{NOVELAI_API_KEY:-}}" ] || {{ echo "NOVELAI_API_KEY is not set." >&2; exit 1; }}
command -v uv >/dev/null || {{ echo "uv is not installed." >&2; exit 1; }}
runner='{runner}'
has='{has}'
out='{images}'
uv run "$runner" validate || exit $?
for f in "$here"/requests/*.request.json; do
  echo "== $(basename "$f")"
  if python "$has" --request "$f" --out-dir "$out"; then echo "already generated; skipping"; continue; fi
  uv run "$runner" estimate --request "$f" || {{ echo "estimate failed; skipping" >&2; continue; }}
  uv run "$runner" generate --request "$f" --out-dir "$out" || echo "generate skipped or failed" >&2
done
python '{book}' --project-dir '{project}' --title '{book_title}'
"""

UPDATE_PS1 = r"""# Rebuild the book HTML ({index}) from the images generated so far. No API key needed.
#   powershell -ExecutionPolicy Bypass -File "{self_rel}"
$ErrorActionPreference = 'Stop'
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
Set-Location (Resolve-Path (Join-Path $here '{up}')).Path
python '{book}' --project-dir '{project}' --title '{book_title}'
"""

UPDATE_SH = r"""#!/usr/bin/env bash
# Rebuild the book HTML ({index}) from the images generated so far. No API key needed.
here="$(cd "$(dirname "${{BASH_SOURCE[0]}}")" && pwd)"
cd "$here/{up}" || exit 1
python '{book}' --project-dir '{project}' --title '{book_title}'
"""

README = """{title}

Generate the book pages (you run this yourself; the agent does not):
  PowerShell : $env:NOVELAI_API_KEY = "<key>"
               powershell -ExecutionPolicy Bypass -File {ps1}
  bash       : export NOVELAI_API_KEY=...
               bash {sh}
The key lives only in that shell session. Never put it in a file.
The script skips pages whose image already exists, estimates each request before generating, and
rebuilds the book HTML at the end.

Rebuild only the HTML (no key needed), e.g. after adding or replacing images by hand:
  PowerShell : powershell -ExecutionPolicy Bypass -File {upd_ps1}
  bash       : bash {upd_sh}
Open {index} in a browser.

Check every generated image by eye: age impression (adult look), character consistency, composition,
private background, and that no excluded element appeared (genital detail, pubic hair, sex acts,
forced/unwilling cues). Discard and re-roll any image that fails; never add youthful-looking tags.
To redo a page on purpose, move the old png and its manifest/<stem>.json into
images/<character>/superseded/ first.
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--spec", required=True)
    ap.add_argument("--project-dir", required=True)
    ap.add_argument("--user-run-dir", default="user-run-scripts")
    ap.add_argument("--chapter", help="comma-separated chapter ids ('cover' for the cover); default all")
    ap.add_argument("--rating", help="override defaults.rating for non-explicit cuts")
    ap.add_argument("--suffix", default="", help="revision suffix, e.g. v2")
    args = ap.parse_args()

    spec = json.loads(Path(args.spec).read_text(encoding="utf-8"))
    validate(spec)
    cwd = Path.cwd()
    project = Path(args.project_dir)
    req_dir = project / "requests"
    rating = args.rating or spec["defaults"].get("rating", "sensitive")
    only = set(args.chapter.split(",")) if args.chapter else None
    theme = slug(spec.get("theme", "book")) or "book"
    cname = spec["character"]["name"]
    skill_dir = Path(__file__).resolve().parents[1]
    skills_root = skill_dir.parent
    runner = rel(skills_root / "novelai-imagegen" / "scripts" / "novelai_image.py", cwd)
    has = rel(skill_dir / "scripts" / "has_output.py", cwd)
    book = rel(skill_dir / "scripts" / "build_book.py", cwd)
    images = rel(project / "images", cwd)
    udir = Path(args.user_run_dir) / f"{cname}-{theme}"
    book_title = spec.get("title", spec.get("project", project.name))

    cells, md, written, skipped = [], [f"## {cname} (seed `{spec['character']['seed']}`)", ""], 0, 0

    def emit(kind, container, cut, chapter_id, user_run):
        nonlocal written, skipped
        for variant in variants(cut):
            stem = "-".join([cname, chapter_id, cut["id"] if kind == "cut" else "cover"] + ([variant] if variant else []))
            stem = stem.replace("-cover-cover", "-cover")
            base, req = build(spec, container, cut, variant, rating, args.suffix, stem)
            target = (udir / "requests") if user_run else req_dir
            path = target / f"{base}.request.json"
            if not only or chapter_id in only:
                target.mkdir(parents=True, exist_ok=True)
                if path.exists():
                    skipped += 1
                else:
                    path.write_text(json.dumps(req, ensure_ascii=False, indent=2), encoding="utf-8")
                    written += 1
            cells.append({
                "kind": kind, "character": cname, "chapter": chapter_id, "cut": cut.get("id", "cover"),
                "label": cut.get("label", cut.get("id", "cover")), "class": cut["class"], "class_label": CLASS_LABEL[cut["class"]],
                "facing": cut.get("facing", ""), "variant": variant, "stem": stem, "seed": req["seed"],
                "orientation": req["orientation"], "script_only": user_run, "request": rel(path, cwd),
            })
            md.extend([f"### {base}{' ※ユーザー実行' if user_run else ''}", "",
                       f"class: `{cut['class']}` / variant: `{variant or '-'}` / shot: `{cut['shot']}`", "",
                       "```", req["prompt"], "```", "", f"negative: `{req['negative_prompt']}`", ""])

    cover = spec["cover"]
    emit("cover", cover, cover, "cover", False)
    for chp in spec["chapters"]:
        for cut in chp["cuts"]:
            emit("cut", chp, cut, chp["id"], True)

    if (udir / "requests").exists() and any((udir / "requests").glob("*.request.json")):
        up = rel(cwd, udir)
        kw = dict(title=f"{cname} / {theme}", up=up, runner=runner, images=images, has=has, book=book,
                  project=rel(project, cwd), book_title=book_title, index=rel(project / "index.html", cwd))
        files = {"run.ps1": PS1, "run.sh": SH, "update-book.ps1": UPDATE_PS1, "update-book.sh": UPDATE_SH}
        for name, tpl in files.items():
            sp = udir / name
            if not sp.exists():
                sp.write_text(tpl.format(self_rel=(udir / name).as_posix(), **kw), encoding="utf-8", newline="\n")
        rp = udir / "README.txt"
        if not rp.exists():
            rp.write_text(README.format(
                title=kw["title"], index=kw["index"], ps1=(udir / "run.ps1").as_posix(), sh=(udir / "run.sh").as_posix(),
                upd_ps1=(udir / "update-book.ps1").as_posix(), upd_sh=(udir / "update-book.sh").as_posix()),
                encoding="utf-8", newline="\n")

    project.mkdir(parents=True, exist_ok=True)
    (project / "manifest.json").write_text(json.dumps({
        "project": spec.get("project", project.name), "title": book_title, "theme": spec.get("theme", ""),
        "character": cname, "seed": spec["character"]["seed"],
        "chapters": [{"id": c["id"], "title": c.get("title", c["id"]), "mode": c.get("mode", "cuts")}
                     for c in spec["chapters"]],
        "cells": cells}, ensure_ascii=False, indent=2), encoding="utf-8")
    (project / "prompts.md").write_text("# Prompts\n\n" + "\n".join(md), encoding="utf-8")
    print(json.dumps({"written": written, "skipped_existing": skipped, "cells": len(cells),
                      "agent_cells": sum(not c["script_only"] for c in cells),
                      "user_run_cells": sum(c["script_only"] for c in cells),
                      "user_run_dir": str(udir)}, ensure_ascii=False))


if __name__ == "__main__":
    sys.exit(main())
